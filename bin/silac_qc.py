COMPARISON_FIELDS = ["fraction_group", "runs", "numerator_channel", "reference_channel",
                     "normalization", "numerator_label_definition", "reference_label_definition",
                     "numerator_sample", "reference_sample", "numerator_condition", "reference_condition"]
SUMMARY_FIELDS = ["level"] + COMPARISON_FIELDS + [
    "total_entities", "reported", "not_reported", "non_positive", "non_finite",
    "coverage", "median_ratio", "median_log2_ratio", "q1_log2", "q3_log2",
    "iqr_log2", "ratio_count_min", "ratio_count_median", "ratio_count_max",
]
BENCHMARK_FIELDS = ["peptide_class"] + COMPARISON_FIELDS + [
    "expected_ratio", "total_entities", "reported", "coverage", "median_ratio",
    "median_log2_ratio", "iqr_log2", "median_bias_percent", "median_log2_error",
]


def read_table(path, fields):
    with path.open(newline="") as handle:
        reader = csv.DictReader(handle, delimiter="\t")
        if reader.fieldnames != fields:
            raise ValueError(f"Unexpected ratio table header: {path}")
        rows = list(reader)
    if any(None in row or any(value is None for value in row.values()) for row in rows):
        raise ValueError(f"Malformed ratio table row: {path}")
    return rows


def validate_export(rows, expected, fields):
    """Reject stale tables or altered quantities before calculating QC."""
    if len(rows) != len(expected):
        raise ValueError("Ratio table row count does not match its scientific sources")
    # Tables generated by the exporter have deterministic order. Sorting complete
    # records permits users to sort a TSV without changing its scientific meaning.
    identities = [field for field in fields if field not in ("ratio", "log2_ratio", "ratio_count")]
    key = lambda row: tuple(str(row[field]) for field in identities)
    actual_sorted = sorted(rows, key=key)
    expected_sorted = sorted(expected, key=key)
    for actual, stored in zip(actual_sorted, expected_sorted):
        for field in fields:
            value = stored[field]
            if field in ("ratio", "log2_ratio") and value is not None:
                number = float(actual[field])
                matches = math.isfinite(number) and math.isclose(number, value, rel_tol=1e-12, abs_tol=1e-12)
            else:
                matches = actual[field] == ("null" if value is None else str(value))
            if not matches:
                raise ValueError(f"Ratio table differs from its scientific sources: {field}")


def quantile(sorted_values, probability):
    if not sorted_values:
        return None
    position = (len(sorted_values) - 1) * probability
    lower = math.floor(position)
    upper = math.ceil(position)
    return sorted_values[lower] + (position - lower) * (sorted_values[upper] - sorted_values[lower])


def distribution(rows):
    reported = [row for row in rows if row["ratio_status"] == "reported"]
    values = [float(row["ratio"]) for row in reported]
    logs = sorted(math.log2(value) for value in values)
    counts = [int(row["ratio_count"]) for row in reported if row["ratio_count"] != "null"]
    statuses = Counter(row["ratio_status"] for row in rows)
    q1, q3 = quantile(logs, 0.25), quantile(logs, 0.75)
    return {
        "total_entities": len(rows),
        **{status: statuses[status] for status in ("reported", "not_reported", "non_positive", "non_finite")},
        "coverage": len(reported) / len(rows) if rows else None,
        "median_ratio": statistics.median(values) if values else None,
        "median_log2_ratio": statistics.median(logs) if logs else None,
        "q1_log2": q1, "q3_log2": q3,
        "iqr_log2": q3 - q1 if logs else None,
        "ratio_count_min": min(counts) if counts else None,
        "ratio_count_median": statistics.median(counts) if counts else None,
        "ratio_count_max": max(counts) if counts else None,
    }


def summarize_ratios(peptides, proteins):
    summaries = []
    grouped = {}
    for level, rows in (("peptide", peptides), ("protein", proteins)):
        comparisons = defaultdict(list)
        for row in rows:
            comparisons[tuple(row[field] for field in COMPARISON_FIELDS)].append(row)
        for identity, observations in sorted(comparisons.items()):
            summary = dict(zip(COMPARISON_FIELDS, identity)) | {"level": level} | distribution(observations)
            summaries.append(summary)
            grouped[(level, identity)] = observations
    return summaries, grouped


def score_summary(rows, field, description):
    # Preserve arbitrary score descriptions; never reinterpret a PEP or search
    # score as a q-value simply because it occupies search_engine_score[1].
    is_qvalue = bool(re.search(r"q[- ]?value", description, re.IGNORECASE))
    values = []
    for row in rows:
        value = row.get(field, "null")
        if value not in ("", "null"):
            number = float(value)
            if math.isfinite(number):
                values.append(number)
    return {"description": description or None, "is_qvalue": is_qvalue,
            "reported_scores": len(values), "missing_scores": len(rows) - len(values),
            "max_reported_qvalue": max(values) if is_qvalue and values else None}


def decoy_summary(rows, field):
    annotations = Counter(row.get(field, "null") for row in rows)
    return {"target_rows": annotations["0"], "decoy_rows": annotations["1"],
            "unknown_rows": len(rows) - annotations["0"] - annotations["1"]}


def read_identifications(path):
    metadata, headers, rows = {}, {}, defaultdict(list)
    with path.open(newline="") as handle:
        for line_number, record in enumerate(csv.reader(handle, delimiter="\t"), 1):
            if not record:
                continue
            tag = record[0]
            if tag == "MTD":
                if len(record) != 3:
                    raise ValueError(f"Malformed mzTab metadata at line {line_number}")
                metadata[record[1]] = record[2]
            elif tag in ("PRH", "PEH", "PSH"):
                headers[tag[:2]] = record
            elif tag in ("PRT", "PEP", "PSM"):
                header = headers.get(tag[:2])
                if header is None or len(header) != len(record):
                    raise ValueError(f"Malformed mzTab {tag} row at line {line_number}")
                rows[tag].append(dict(zip(header, record)))
    psms = rows["PSM"]
    run_names = {key.removesuffix("-location"): Path(unquote(value.removeprefix("file://"))).stem
                 for key, value in metadata.items() if re.fullmatch(r"ms_run\[\d+\]-location", key)}
    per_run = {run: [] for run in run_names.values()}
    psm_identities = set()
    unresolved = 0
    for row in psms:
        spectrum = row.get("spectra_ref", "null")
        if spectrum in ("", "null"):
            unresolved += 1
            continue
        # Multi-spectrum references cannot unambiguously be assigned to one run.
        run_reference = spectrum.split(":", 1)[0]
        if "|" in spectrum or run_reference not in run_names:
            unresolved += 1
            continue
        per_run[run_names[run_reference]].append(row)
        psm_identities.add(tuple(row.get(field, "null") for field in
                                 ("spectra_ref", "sequence", "modifications", "charge")))
    psm_score = metadata.get("psm_search_engine_score[1]", "")
    result = {
        "mztab_rows": {tag: len(rows[tag]) for tag in ("PRT", "PEP", "PSM")},
        "protein_row_types": dict(sorted(Counter(row.get("opt_global_result_type", "unknown")
                                                for row in rows["PRT"]).items())),
        "unique_resolved_psms": len(psm_identities), "unresolved_psm_rows": unresolved,
        "distinct_peptide_sequences": len({row["sequence"] for row in rows["PEP"]}),
        "distinct_modified_peptides": len({(row["sequence"], row["modifications"]) for row in rows["PEP"]}),
        "psm_decoy_annotations": decoy_summary(psms, "opt_global_cv_MS:1002217_decoy_peptide"),
        "protein_decoy_annotations": decoy_summary(rows["PRT"], "opt_global_cv_PRIDE:0000303_decoy_hit"),
        "psm_score": score_summary(psms, "search_engine_score[1]", psm_score),
        "protein_score": score_summary(rows["PRT"], "best_search_engine_score[1]",
                                       metadata.get("protein_search_engine_score[1]", "")),
        "per_run": [{"run": run, "psm_rows": len(observations),
                     "unique_psms": len({tuple(row.get(field, "null") for field in
                                              ("spectra_ref", "sequence", "modifications", "charge"))
                                         for row in observations}),
                     "score": score_summary(observations, "search_engine_score[1]", psm_score),
                     "decoy_annotations": decoy_summary(observations, "opt_global_cv_MS:1002217_decoy_peptide")}
                    for run, observations in sorted(per_run.items())],
    }
    return result, {key: value for key, value in metadata.items() if re.fullmatch(r"software\[\d+\]", key)}


def read_processing(path):
    root = ET.parse(path).getroot()
    reference, labels, normalized = read_settings(root)
    node = next(node for node in root.findall("dataProcessing")
                if node.find("software") is not None and node.find("software").get("name") == "MS1LabeledWorkflow")
    parameters = {key.removeprefix("parameter: "): value for key, value in user_params(node).items()
                  if key.startswith("parameter: ")}
    counts = Counter()
    maps = {column.get("id"): Path(column.get("name")).stem for column in root.findall("./mapList/map")}
    features = root.findall("./consensusElementList/consensusElement")
    for feature in features:
        runs = {maps[element.get("map")] for element in feature.findall("./groupedElementList/element")}
        counts.update(runs)
    return {"software": node.find("software").attrib,
            "reference_channel": reference, "label_definitions": [f"[{label}]" for label in labels],
            "ratio_normalization_enabled": normalized, "parameters": parameters,
            "final_linked_features": len(features), "final_features_per_run": dict(sorted(counts.items()))}


def read_benchmark(path):
    config = json.loads(path.read_text())
    if config.get("schema_version") != 1:
        raise ValueError("Unsupported benchmark schema version")
    classes = config["peptide_classes"]
    if not classes:
        raise ValueError("Benchmark must define peptide classes")
    for name, counts in classes.items():
        if not counts or any(not re.fullmatch("[A-Z]", residue) or type(count) is not int or count < 0
                             for residue, count in counts.items()):
            raise ValueError(f"Invalid residue-count selector: {name}")
    for comparison in config["comparisons"]:
        if not comparison["runs"] or len(set(comparison["runs"])) != len(comparison["runs"]):
            raise ValueError("Benchmark runs must be a non-empty, distinct list")
        if comparison["normalization"] not in ("raw", "normalized"):
            raise ValueError("Benchmark normalization must be raw or normalized")
        for name, expected in comparison["expected_ratios"].items():
            if name not in classes or not math.isfinite(float(expected)) or float(expected) <= 0:
                raise ValueError("Expected benchmark ratios must be positive and have a defined peptide class")
    return config


def summarize_benchmark(peptides, config):
    result, plot_groups, unmatched = [], [], []
    if config is None:
        return result, plot_groups, unmatched
    for selector in config["comparisons"]:
        matching = [row for row in peptides
                    if sorted(row["runs"].split(";")) == sorted(selector["runs"])
                    and all(row[field] == selector[field] for field in
                            ("numerator_label_definition", "reference_label_definition", "normalization"))]
        if not matching:
            unmatched.append(selector)
            continue
        comparisons = defaultdict(list)
        for row in matching:
            comparisons[tuple(row[field] for field in COMPARISON_FIELDS)].append(row)
        for identity, rows in sorted(comparisons.items()):
            for name, expected in selector["expected_ratios"].items():
                selected = [row for row in rows if all(row["sequence"].count(residue) == count
                                                       for residue, count in config["peptide_classes"][name].items())]
                expected = float(expected)
                summary = dict(zip(COMPARISON_FIELDS, identity)) | distribution(selected)
                summary.update({"peptide_class": name, "expected_ratio": expected,
                                "median_bias_percent": (summary["median_ratio"] / expected - 1) * 100
                                if summary["median_ratio"] is not None else None,
                                "median_log2_error": summary["median_log2_ratio"] - math.log2(expected)
                                if summary["median_log2_ratio"] is not None else None})
                result.append(summary)
                plot_groups.append((summary, selected))
    return result, plot_groups, unmatched


def analyze(peptide_path, protein_path, mztab, consensusxml, design, benchmark=None):
    peptides = read_table(peptide_path, PEPTIDE_FIELDS)
    proteins = read_table(protein_path, PROTEIN_FIELDS)
    expected_peptides, expected_proteins = export_ratios(mztab, consensusxml, design)
    validate_export(peptides, expected_peptides, PEPTIDE_FIELDS)
    validate_export(proteins, expected_proteins, PROTEIN_FIELDS)
    summaries, grouped = summarize_ratios(peptides, proteins)
    identification, software = read_identifications(mztab)
    processing = read_processing(consensusxml)
    benchmark_rows, benchmark_plots, unmatched = summarize_benchmark(peptides, benchmark)
    identities = lambda rows, fields: len({tuple(row[field] for field in fields) for row in rows})
    reported_raw = lambda rows: [row for row in rows if row["normalization"] == "raw" and row["ratio_status"] == "reported"]
    metrics = {
        "schema_version": 1,
        "definitions": {
            "coverage_denominator": "All exported experiment-wide entities in each fraction-group/channel/normalization comparison",
            "quantiles": "Linear interpolation at (n-1)*p (inclusive/type 7); a singleton has zero IQR",
            "protein_support": "Stored contributing peptide-ratio count; not biological replication",
        },
        "inputs": {name: {"path": str(path), "sha256": hashlib.sha256(path.read_bytes()).hexdigest()}
                   for name, path in (("peptide_ratios", peptide_path), ("protein_ratios", protein_path),
                                      ("mztab", mztab), ("consensusxml", consensusxml), ("design", design))},
        "software": software, "processing": processing, "identification": identification,
        "entities": {"peptides_in_export": identities(peptides, ("sequence", "modifications")),
                     "protein_groups_in_export": identities(proteins, ("protein_group",)),
                     "peptides_with_raw_ratio": identities(reported_raw(peptides), ("sequence", "modifications")),
                     "protein_groups_with_raw_ratio": identities(reported_raw(proteins), ("protein_group",))},
        "comparisons": summaries, "benchmark_name": benchmark.get("name") if benchmark else None,
        "benchmark": benchmark_rows, "unmatched_benchmark_comparisons": unmatched,
        "notes": [
            "Missingness uses experiment-wide exported entities, not just entities detected in each run.",
            "not_reported does not distinguish undetected signal from insufficient evidence.",
            "Raw and normalized estimates are summarized separately; no normalization or imputation is applied.",
            "mzTab protein detail and group rows are counted separately from full inferred protein groups.",
            "Q-values describe software-reported filtering, not an independent measurement of true FDR.",
            "Final linked features are available; initial detection and label-rejection totals require task logs.",
            "Benchmark statistics describe quantified peptides; class coverage includes missing estimates.",
            "No scientific pass/fail thresholds are applied.",
        ],
    }
    return metrics, grouped, benchmark_plots


def comparison_title(row):
    return (f"Group {row['fraction_group']} · {row['runs']} · "
            f"channel {row['numerator_channel']}/{row['reference_channel']} · {row['normalization']}")


def make_plots(outdir, summaries, grouped, benchmark_plots):
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError as error:
        raise ValueError("Plots require Matplotlib; use the silac environment or pass --no-plots") from error
    folder = outdir / "plots"
    folder.mkdir(parents=True, exist_ok=True)
    figures = []

    def save(figure, filename, caption):
        figure.tight_layout()
        png = folder / f"{filename}.png"
        pdf = folder / f"{filename}.pdf"
        figure.savefig(png, dpi=160)
        figure.savefig(pdf)
        plt.close(figure)
        figures.append({"caption": caption, "png": str(png.relative_to(outdir)),
                        "pdf": str(pdf.relative_to(outdir)),
                        "image": base64.b64encode(png.read_bytes()).decode("ascii")})

    comparisons = sorted({key[1] for key in grouped})
    for index, identity in enumerate(comparisons, 1):
        metadata = dict(zip(COMPARISON_FIELDS, identity))
        title = comparison_title(metadata)
        figure, axes = plt.subplots(1, 2, figsize=(10, 3.8))
        all_logs = [math.log2(float(row["ratio"])) for level in ("peptide", "protein")
                    for row in grouped.get((level, identity), []) if row["ratio_status"] == "reported"]
        bounds = (min(all_logs), max(all_logs)) if all_logs else (-1, 1)
        if bounds[0] == bounds[1]:
            bounds = (bounds[0] - 0.5, bounds[1] + 0.5)
        for axis, level in zip(axes, ("peptide", "protein")):
            values = [math.log2(float(row["ratio"])) for row in grouped.get((level, identity), [])
                      if row["ratio_status"] == "reported"]
            axis.hist(values, bins=30, range=bounds, color="#287e8a", alpha=0.85)
            if values:
                axis.axvline(statistics.median(values), color="#b75337", linestyle="--", label="Median")
                axis.legend()
            else:
                axis.text(0.5, 0.5, "No reported ratios", transform=axis.transAxes, ha="center")
            axis.set(title=f"{level.capitalize()} ratios (n={len(values)})", xlabel="log2(numerator/reference)", ylabel="Entities")
        figure.suptitle(title, fontsize=10)
        save(figure, f"ratios_{index:03d}", title)

        figure, axis = plt.subplots(figsize=(6, 3.5))
        counts = [int(row["ratio_count"]) for row in grouped.get(("protein", identity), [])
                  if row["ratio_status"] == "reported" and row["ratio_count"] != "null"]
        axis.hist(counts, bins=min(30, max(counts) - min(counts) + 1) if counts else 1, color="#287e8a")
        axis.set(title=title, xlabel="Stored contributing peptide-ratio count", ylabel="Protein groups")
        if not counts:
            axis.text(0.5, 0.5, "No reported support counts", transform=axis.transAxes, ha="center")
        save(figure, f"protein_support_{index:03d}", f"Protein support · {title}")

    if summaries:
        figure, axis = plt.subplots(figsize=(10, max(3, len(summaries) * 0.45)))
        labels = [f"{row['level']} · group {row['fraction_group']} · {row['numerator_channel']}/{row['reference_channel']} · {row['normalization']}"
                  for row in summaries]
        axis.barh(range(len(summaries)), [row["coverage"] or 0 for row in summaries], color="#287e8a")
        axis.set_yticks(range(len(summaries)), labels)
        axis.set(xlim=(0, 1), xlabel="Reported ratios / all exported entities in comparison", title="Ratio coverage")
        save(figure, "coverage", "Coverage uses exported experiment-wide entities as the denominator")

    for index, (summary, rows) in enumerate(benchmark_plots, 1):
        values = [math.log2(float(row["ratio"])) for row in rows if row["ratio_status"] == "reported"]
        figure, axis = plt.subplots(figsize=(6, 3.5))
        axis.hist(values, bins=30, color="#287e8a", alpha=0.85)
        axis.axvline(math.log2(summary["expected_ratio"]), color="#263b67", label="Expected")
        if values:
            axis.axvline(statistics.median(values), color="#b75337", linestyle="--", label="Median")
        axis.legend()
        caption = f"{summary['peptide_class']} · {comparison_title(summary)}"
        axis.set(title=caption, xlabel="log2(numerator/reference)", ylabel="Modified peptides")
        save(figure, f"benchmark_{index:03d}", caption)
    return figures


def format_value(value):
    if value is None:
        return "—"
    if isinstance(value, float):
        return f"{value:.4g}"
    return str(value)


def html_table(rows, columns):
    headings = "".join(f"<th>{html.escape(label)}</th>" for _, label in columns)
    body = "".join("<tr>" + "".join(f"<td>{html.escape(format_value(row.get(field)))}</td>"
                                    for field, _ in columns) + "</tr>" for row in rows)
    return f'<div class="table-scroll"><table><thead><tr>{headings}</tr></thead><tbody>{body}</tbody></table></div>'


