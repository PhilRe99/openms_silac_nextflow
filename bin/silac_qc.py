def write_summary(path, rows, fields):
    with path.open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields, delimiter="\t", lineterminator="\n", extrasaction="ignore")
        writer.writeheader()
        writer.writerows({key: "null" if value is None else value for key, value in row.items()} for row in rows)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for option in ("peptide-ratios", "protein-ratios", "mztab", "consensusxml", "design", "outdir"):
        parser.add_argument(f"--{option}", type=Path, required=True)
    parser.add_argument("--benchmark", type=Path, help="Optional benchmark definition JSON")
    parser.add_argument("--no-plots", action="store_true", help="Generate tables/report using only the Python standard library")
    args = parser.parse_args()
    try:
        config = read_benchmark(args.benchmark) if args.benchmark else None
        metrics, grouped, benchmark_plots = analyze(args.peptide_ratios, args.protein_ratios,
                                                  args.mztab, args.consensusxml, args.design, config)
        if args.benchmark:
            metrics["inputs"]["benchmark"] = {"path": str(args.benchmark),
                                              "sha256": hashlib.sha256(args.benchmark.read_bytes()).hexdigest()}
        args.outdir.mkdir(parents=True, exist_ok=True)
        figures = [] if args.no_plots else make_plots(args.outdir, metrics["comparisons"], grouped, benchmark_plots)
        metrics["plots"] = [{key: value for key, value in figure.items() if key != "image"} for figure in figures]
        (args.outdir / "metrics.json").write_text(json.dumps(metrics, indent=2, allow_nan=False) + "\n")
        write_summary(args.outdir / "summary.tsv", metrics["comparisons"], SUMMARY_FIELDS)
        write_summary(args.outdir / "benchmark.tsv", metrics["benchmark"], BENCHMARK_FIELDS)
        (args.outdir / "report.html").write_text(render_report(metrics, figures))
    except (ValueError, KeyError, TypeError, OSError, ET.ParseError) as error:
        parser.exit(1, f"Cannot generate SILAC QC: {error}\n")
    print(f"QC report: {args.outdir / 'report.html'}")
    print(f"Comparisons: {len(metrics['comparisons'])}; benchmark summaries: {len(metrics['benchmark'])}")


if __name__ == "__main__":
    main()
