#!/usr/bin/env python3

import csv
import json
import os
import sys
from collections import OrderedDict

if len(sys.argv) != 6:
    raise SystemExit(
        "Usage: build_ms1_groups.py "
        "<experimental_design.tsv> <files.tsv> <out_dir> <groups.tsv> <members.tsv>"
    )

design_path, files_path, out_dir, groups_path, members_path = sys.argv[1:]

# OpenMS experimental design = file table, blank line, sample table
with open(design_path, newline="") as fh:
    lines = list(fh)

separator = next(i for i, line in enumerate(lines) if not line.strip())

file_reader = csv.DictReader(lines[:separator], delimiter="\t")
sample_reader = csv.DictReader(lines[separator + 1:], delimiter="\t")

file_rows = list(file_reader)
sample_rows = list(sample_reader)

# Per-file state generated by the Bash workflow
with open(files_path, newline="") as fh:
    states = list(csv.DictReader(fh, delimiter="\t"))

# One MS1LabeledWorkflow call per exact label chemistry
chemistry_groups = OrderedDict()
for state in states:
    chemistry_groups.setdefault(state["labels"], []).append(state)

with open(groups_path, "w", newline="") as gf, \
     open(members_path, "w", newline="") as mf:

    group_writer = csv.writer(gf, delimiter="\t", lineterminator="\n")
    member_writer = csv.writer(mf, delimiter="\t", lineterminator="\n")

    group_writer.writerow(["group", "labels", "design"])
    member_writer.writerow(["group", "mzml", "idxml"])

    for index, (labels, group_states) in enumerate(chemistry_groups.items(), start=1):
        group = f"group_{index}"
        group_dir = os.path.join(out_dir, group)
        os.makedirs(group_dir, exist_ok=True)

        group_design = os.path.join(group_dir, "experimental_design.tsv")

        state_by_base = {
            state["base"]: state
            for state in group_states
        }

        # Global experimental-design label IDs -> local 1..N channel IDs
        label_map_by_base = {}
        for state in group_states:
            with open(state["config"]) as fh:
                config = json.load(fh)

            global_labels = [str(label) for label in config["labels"]]
            label_map_by_base[state["base"]] = {
                old: str(local)
                for local, old in enumerate(global_labels, start=1)
            }

        selected = []

        for original in file_rows:
            base = os.path.splitext(os.path.basename(original["Spectra_Filepath"]))[0]

            if base not in state_by_base:
                continue

            row = dict(original)

            # Use the actual file passed downstream (original or centroided)
            row["Spectra_Filepath"] = state_by_base[base]["mzml"]

            # Example: global duplex labels 1,3 -> local labels 1,2
            row["Label"] = label_map_by_base[base][str(row["Label"])]

            # Fraction is deliberately left unchanged
            selected.append(row)

        # Fraction_Group only needs consecutive IDs inside this subset.
        # The grouping relation is preserved; Fraction itself is untouched.
        original_fraction_groups = sorted(
            {row["Fraction_Group"] for row in selected},
            key=int,
        )
        fraction_group_map = {
            old: str(local)
            for local, old in enumerate(original_fraction_groups, start=1)
        }

        for row in selected:
            row["Fraction_Group"] = fraction_group_map[row["Fraction_Group"]]

        used_samples = {row["Sample"] for row in selected}

        with open(group_design, "w", newline="") as out:
            fw = csv.DictWriter(
                out,
                fieldnames=file_reader.fieldnames,
                delimiter="\t",
                lineterminator="\n",
            )
            fw.writeheader()
            fw.writerows(selected)

            out.write("\n")

            sw = csv.DictWriter(
                out,
                fieldnames=sample_reader.fieldnames,
                delimiter="\t",
                lineterminator="\n",
            )
            sw.writeheader()
            for row in sample_rows:
                if row.get("Sample") in used_samples:
                    sw.writerow(row)

        group_writer.writerow([group, labels, group_design])

        for state in group_states:
            member_writer.writerow([
                group,
                state["mzml"],
                state["idxml"],
            ])
